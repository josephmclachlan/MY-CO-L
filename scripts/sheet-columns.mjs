// Reads supabase/migrations/*.sql and writes src/lib/sheets/columns.gen.ts:
// every table's columns, the kind of value each holds, and the fixed choice lists from the database's check rules.
// The Google Sheet uses it for number formats, tick boxes and dropdowns, and the sync uses it to check sheet edits.
// Run: node scripts/sheet-columns.mjs   (the sheets test fails when the file is out of date)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

export function splitTop(s) {
  const out = []
  let depth = 0
  let q = false
  let cur = ''
  for (const ch of s) {
    if (ch === "'") q = !q
    if (!q && ch === '(') depth++
    if (!q && ch === ')') depth--
    if (!q && depth === 0 && ch === ',') {
      out.push(cur.trim())
      cur = ''
    } else cur += ch
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

function kindOf(type) {
  const t = type.toLowerCase()
  if (t.endsWith('[]') || t.startsWith('jsonb') || t.startsWith('json')) return 'json'
  if (/^(numeric|integer|int|bigint|smallint|real|double|decimal|float)/.test(t)) return 'number'
  if (t.startsWith('boolean') || t === 'bool') return 'bool'
  if (t.startsWith('timestamptz') || t.startsWith('timestamp')) return 'datetime'
  if (t.startsWith('date')) return 'date'
  return 'text'
}

function choicesIn(text, col) {
  const m = new RegExp(`\\b${col}\\s+in\\s*\\(([^)]*)\\)`, 'i').exec(text)
  if (!m) return null
  const vals = [...m[1].matchAll(/'((?:[^']|'')*)'/g)].map((x) => x[1].replace(/''/g, "'"))
  return vals.length ? vals : null
}

export function parseMigrations(texts) {
  const tables = {}
  const cons = {} // table.constraint -> column
  const colDef = (table, piece) => {
    const m = /^"?(\w+)"?\s+([\w\s[\]().,]+?)(?=\s+(?:not|null|default|primary|references|check|unique|generated|constraint)\b|$)/i.exec(piece)
    if (!m) return
    const name = m[1]
    if (/^(primary|unique|check|foreign|constraint|exclude)$/i.test(name)) return
    const type = m[2].trim()
    tables[table][name] = { kind: kindOf(type), required: /\bnot\s+null\b/i.test(piece) && !/\bdefault\b/i.test(piece) && name !== 'id', choices: choicesIn(piece, name) }
  }
  for (const raw of texts) {
    const text = raw.replace(/--[^\n]*/g, '')
    // Function bodies ($$ ... $$) can hold semicolons and table names: drop them.
    const noFn = text.replace(/\$\w*\$[\s\S]*?\$\w*\$/g, '')
    for (const st0 of noFn.split(';')) {
      const st = st0.trim()
      let m = /^create\s+table\s+(?:if\s+not\s+exists\s+)?public\.(\w+)\s*\(([\s\S]*)\)\s*$/i.exec(st)
      if (m) {
        const t = m[1]
        tables[t] = tables[t] ?? {}
        for (const piece of splitTop(m[2])) {
          if (/^(primary|unique|foreign|constraint|exclude)\b/i.test(piece)) continue
          if (/^check\b/i.test(piece)) {
            for (const c of Object.keys(tables[t])) {
              const ch = choicesIn(piece, c)
              if (ch) tables[t][c].choices = ch
            }
            continue
          }
          colDef(t, piece)
        }
        continue
      }
      m = /^alter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?public\.(\w+)\s+([\s\S]*)$/i.exec(st)
      if (!m || !tables[m[1]]) continue
      const t = m[1]
      for (const act of splitTop(m[2])) {
        let a = /^add\s+column\s+(?:if\s+not\s+exists\s+)?([\s\S]*)$/i.exec(act)
        if (a) {
          colDef(t, a[1].trim())
          continue
        }
        a = /^drop\s+column\s+(?:if\s+exists\s+)?"?(\w+)"?/i.exec(act)
        if (a) {
          delete tables[t][a[1]]
          continue
        }
        a = /^alter\s+column\s+"?(\w+)"?\s+drop\s+not\s+null/i.exec(act)
        if (a && tables[t][a[1]]) {
          tables[t][a[1]].required = false
          continue
        }
        a = /^add\s+constraint\s+(\w+)\s+check\s*([\s\S]*)$/i.exec(act)
        if (a) {
          for (const c of Object.keys(tables[t])) {
            const ch = choicesIn(a[2], c)
            if (ch) {
              tables[t][c].choices = ch
              cons[`${t}.${a[1]}`] = c
            }
          }
          continue
        }
        a = /^drop\s+constraint\s+(?:if\s+exists\s+)?(\w+)/i.exec(act)
        if (a) {
          const c = cons[`${t}.${a[1]}`] ?? (new RegExp(`^${t}_(\\w+)_check$`).exec(a[1]) || [])[1]
          if (c && tables[t][c]) tables[t][c].choices = null
        }
      }
    }
  }
  return tables
}

export function render(tables) {
  const lines = [
    '// GENERATED by scripts/sheet-columns.mjs from supabase/migrations. Do not edit by hand: run `node scripts/sheet-columns.mjs`.',
    "import type { ColumnSpec } from './types'",
    '',
    'export const DB_COLUMNS: Record<string, Record<string, ColumnSpec>> = {',
  ]
  for (const t of Object.keys(tables).sort()) {
    lines.push(`  ${t}: {`)
    for (const [c, s] of Object.entries(tables[t])) {
      const parts = [`kind: '${s.kind}'`]
      if (s.required) parts.push('required: true')
      if (s.choices) parts.push(`choices: ${JSON.stringify(s.choices).replace(/"/g, "'")}`)
      lines.push(`    ${c}: { ${parts.join(', ')} },`)
    }
    lines.push('  },')
  }
  lines.push('}', '')
  return lines.join('\n')
}

export function generate() {
  const dir = join(root, 'supabase', 'migrations')
  const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
  return render(parseMigrations(files.map((f) => readFileSync(join(dir, f), 'utf8'))))
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'src', 'lib', 'sheets', 'columns.gen.ts'), generate())
  console.log('wrote src/lib/sheets/columns.gen.ts')
}
