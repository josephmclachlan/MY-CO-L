import { GUIDE, GUIDE_GROUPS, type GSection } from './content'

/** The whole guide as one Markdown file (docs/USER-MANUAL.md), made from the same text the USER GUIDE screen shows. */
export function guideMarkdown(pages: GSection[] = GUIDE): string {
  const out: string[] = []
  out.push('# MY/CO/L user manual', '')
  out.push('> Made from `src/guide/` by `npm run docs:guide`. Do not edit this file by hand: change the guide text and run the command again. The same text is on the USER GUIDE screen inside the app (MAINFRAME > USER GUIDE, station 8.1, or type GUIDE).', '')
  out.push('## Contents', '')
  for (const g of GUIDE_GROUPS) {
    const rows = pages.filter((p) => p.group === g)
    if (!rows.length) continue
    out.push(`**${g}**`, '')
    for (const p of rows) out.push(`- [${p.title}](#${anchor(p.title)})`)
    out.push('')
  }
  for (const g of GUIDE_GROUPS) {
    const rows = pages.filter((p) => p.group === g)
    for (const p of rows) {
      out.push(`## ${p.title}`, '', `*${p.what}*`, '')
      for (const b of p.blocks) {
        out.push(`### ${b.h}`, '')
        for (const t of b.text ?? []) out.push(t, '')
        if (b.steps) {
          b.steps.forEach((s, i) => out.push(`${i + 1}. ${s}`))
          out.push('')
        }
        if (b.items) {
          for (const [k, v] of b.items) out.push(`- **${k}**: ${v}`)
          out.push('')
        }
      }
    }
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

/** GitHub's heading link for a title. */
export function anchor(title: string): string {
  return title.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-')
}
